import sharp from 'sharp';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const SRC = process.env.PHOTO_SRC ?? resolve('src/assets/source-photo.jpg');
const OUT = resolve('public');
mkdirSync(OUT, { recursive: true });

// Portrait crop focused on Juliana, keeping a sliver of the Microsoft signage as context.
const CROP = { left: 414, top: 92, width: 384, height: 505 };

async function portrait() {
  const base = sharp(SRC).extract(CROP).resize(960, 1263, { fit: 'cover', kernel: 'lanczos3' });
  await base.clone().webp({ quality: 86 }).toFile(resolve(OUT, 'juliana-portrait.webp'));
  await base.clone().avif({ quality: 62 }).toFile(resolve(OUT, 'juliana-portrait.avif'));
  await base.clone().jpeg({ quality: 88, mozjpeg: true }).toFile(resolve(OUT, 'juliana-portrait.jpg'));

  await sharp(SRC)
    .extract(CROP)
    .resize(480, 632, { fit: 'cover', kernel: 'lanczos3' })
    .webp({ quality: 82 })
    .toFile(resolve(OUT, 'juliana-portrait-480.webp'));

  const blur = await sharp(SRC).extract(CROP).resize(20, 26).blur(1.2).webp({ quality: 40 }).toBuffer();
  writeFileSync(
    resolve('src/assets/portrait-placeholder.ts'),
    `// Generated by scripts/build-assets.mjs - do not edit by hand.\nexport const portraitPlaceholder =\n  'data:image/webp;base64,${blur.toString('base64')}';\n`,
  );
}

async function og() {
  const photo = await sharp(SRC)
    .extract(CROP)
    .resize(430, 630, { fit: 'cover', position: 'top' })
    .toBuffer();

  const bg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
    <defs>
      <radialGradient id="g1" cx="78%" cy="18%" r="62%">
        <stop offset="0%" stop-color="#ff4d9d" stop-opacity="0.5"/>
        <stop offset="100%" stop-color="#ff4d9d" stop-opacity="0"/>
      </radialGradient>
      <radialGradient id="g2" cx="10%" cy="95%" r="55%">
        <stop offset="0%" stop-color="#b43cff" stop-opacity="0.32"/>
        <stop offset="100%" stop-color="#b43cff" stop-opacity="0"/>
      </radialGradient>
    </defs>
    <rect width="1200" height="630" fill="#07060a"/>
    <rect width="1200" height="630" fill="url(#g1)"/>
    <rect width="1200" height="630" fill="url(#g2)"/>
  </svg>`);

  const fade = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="430" height="630">
    <defs><linearGradient id="f" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0%" stop-color="#07060a" stop-opacity="0.96"/>
      <stop offset="45%" stop-color="#07060a" stop-opacity="0.16"/>
      <stop offset="100%" stop-color="#07060a" stop-opacity="0.04"/>
    </linearGradient></defs>
    <rect width="430" height="630" fill="url(#f)"/>
  </svg>`);

  const text = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
    <style>
      .eyebrow { font: 600 23px 'Segoe UI', Arial, sans-serif; fill:#ff6fae; letter-spacing:5px; }
      .name { font: 800 92px 'Segoe UI', Arial, sans-serif; fill:#ffffff; letter-spacing:-2px; }
      .role { font: 500 32px 'Segoe UI', Arial, sans-serif; fill:#cfc7d6; }
      .meta { font: 600 21px 'Segoe UI', Arial, sans-serif; fill:#8d8398; letter-spacing:3px; }
    </style>
    <text class="eyebrow" x="86" y="186">SOLUTION ENGINEER</text>
    <text class="name" x="82" y="288">Juliana</text>
    <text class="name" x="82" y="380">Moore</text>
    <text class="role" x="86" y="444">AI solutions @ Microsoft</text>
    <text class="role" x="86" y="488">Computer Science @ Mackenzie</text>
    <rect x="86" y="532" width="58" height="3" fill="#ff4d9d"/>
    <text class="meta" x="86" y="582">SAO PAULO, BRAZIL</text>
  </svg>`);

  await sharp(bg)
    .composite([
      { input: photo, left: 770, top: 0 },
      { input: fade, left: 770, top: 0 },
      { input: text, left: 0, top: 0 },
    ])
    .jpeg({ quality: 90, mozjpeg: true })
    .toFile(resolve(OUT, 'og-image.jpg'));
}

function markSvg() {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="#1a1420"/><stop offset="100%" stop-color="#07060a"/>
    </linearGradient>
    <linearGradient id="fg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="#ffa6d2"/><stop offset="100%" stop-color="#ff2f8e"/>
    </linearGradient>
  </defs>
  <rect width="64" height="64" rx="15" fill="url(#bg)"/>
  <rect x="1" y="1" width="62" height="62" rx="14" fill="none" stroke="#ff2f8e" stroke-opacity="0.45"/>
  <text x="32" y="43" text-anchor="middle" font-family="Segoe UI, Arial, sans-serif" font-size="29" font-weight="700" fill="url(#fg)">JM</text>
</svg>`;
}

async function icons() {
  const svg = Buffer.from(markSvg());
  await sharp(svg, { density: 600 }).resize(180, 180).png().toFile(resolve(OUT, 'apple-touch-icon.png'));
  await sharp(svg, { density: 600 }).resize(512, 512).png().toFile(resolve(OUT, 'icon-512.png'));
  await sharp(svg, { density: 600 }).resize(192, 192).png().toFile(resolve(OUT, 'icon-192.png'));
  await sharp(svg, { density: 600 }).resize(48, 48).png().toFile(resolve(OUT, 'favicon.png'));
  writeFileSync(resolve(OUT, 'favicon.svg'), markSvg());
}

await portrait();
await og();
await icons();
console.log('assets built');
